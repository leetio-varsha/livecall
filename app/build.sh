#!/usr/bin/env bash
# Build Livecall.app (menu-bar app) without an Xcode project:
# compile the sources with swiftc, assemble the bundle, sign it.
#
# The capture/hotkey sources are SHARED with the CLI helper (helper/Sources) —
# one implementation, two front-ends. Only the helper's own entry point and its
# parent watchdog are excluded here; inside the app those jobs belong to
# AppState and macOS.
set -euo pipefail

APP_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "$APP_DIR/.." && pwd)"
SRC="$APP_DIR/Livecall/Sources"
SHARED="$REPO_ROOT/helper/Sources"
BUILD="$APP_DIR/build"
APP="$BUILD/Livecall.app"

rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

# Bake the repo path so the app finds core/ regardless of where it's launched.
cat > "$SRC/Generated.swift" <<SWIFT
// AUTO-GENERATED by app/build.sh — do not edit.
enum BuildConfig {
    static let repoRoot = "$REPO_ROOT"
}
SWIFT

# One ObjC translation unit, and it earns its place: installTapOnBus RAISES on
# a format mismatch, and an ObjC exception cannot be caught from Swift — it
# terminated the app three times mid-call. The @try has to be in ObjC.
echo "Compiling the ObjC exception shim…"
mkdir -p "$BUILD/obj"
xcrun clang -c \
  -O2 -fobjc-arc \
  -target arm64-apple-macos14.4 \
  -o "$BUILD/obj/TapInstall.o" \
  "$SHARED/ObjC/TapInstall.m"

echo "Compiling Livecall.app…"
swiftc \
  -O \
  -swift-version 5 \
  -target arm64-apple-macos14.4 \
  -parse-as-library \
  -import-objc-header "$SHARED/ObjC/TapInstall.h" \
  -framework SwiftUI -framework AppKit -framework AVFoundation \
  -framework ScreenCaptureKit -framework CoreMedia -framework CoreAudio \
  -framework CoreGraphics -framework ApplicationServices \
  -o "$APP/Contents/MacOS/Livecall" \
  "$BUILD/obj/TapInstall.o" \
  "$SRC"/*.swift \
  "$SHARED/FrameWriter.swift" \
  "$SHARED/MicCapture.swift" \
  "$SHARED/SystemAudioCapture.swift" \
  "$SHARED/PCMConverter.swift" \
  "$SHARED/CallDetector.swift" \
  "$SHARED/ScreenShot.swift" \
  "$SHARED/HotkeyTap.swift"

cp "$APP_DIR/Livecall/Info.plist" "$APP/Contents/Info.plist"

# Signing identity, best first. What matters is that the identity stays the
# same across rebuilds: then the app's designated requirement is stable and the
# Microphone / Screen Recording / Accessibility / Input Monitoring grants
# survive. Ad-hoc signing hashes the binary itself, so every rebuild looks like
# a different app and macOS asks for all four permissions again.
#   1. $CODESIGN_IDENTITY   — explicit override
#   2. "Apple Development"  — a real cert from your developer account
#   3. "Livecall Self-Signed" — Keychain Access → Certificate Assistant →
#      Create a Certificate… → Code Signing
IDENTITIES=$(security find-identity -p codesigning 2>/dev/null || true)
IDENTITY="${CODESIGN_IDENTITY:-}"
if [ -z "$IDENTITY" ]; then
  IDENTITY=$(printf '%s' "$IDENTITIES" | sed -n 's/.*"\(Apple Development:[^"]*\)".*/\1/p' | head -1)
fi
if [ -z "$IDENTITY" ] && printf '%s' "$IDENTITIES" | grep -q "Livecall Self-Signed"; then
  IDENTITY="Livecall Self-Signed"
fi

if [ -n "$IDENTITY" ]; then
  echo "Signing with: $IDENTITY (TCC grants survive rebuilds)…"
  codesign --force --sign "$IDENTITY" "$APP"
else
  echo "⚠️  No stable signing identity found — ad-hoc signing. macOS will ask"
  echo "   for all four permissions again after every rebuild. See above."
  codesign --force --sign - "$APP"
fi

echo "Built: $APP"
echo "Run:   open \"$APP\"    (first launch asks for mic + screen recording + accessibility)"

# Install into /Applications: a bundle that lives only in app/build/ is often
# invisible to Spotlight, and a copy left in /Applications silently shadows
# every later rebuild — you fix something, relaunch from Spotlight, and run
# week-old code.
#
# Only the primary checkout installs. A linked worktree bakes ITS OWN path into
# BuildConfig.repoRoot above, so installing a worktree build would leave
# /Applications pointing at a directory that `git worktree remove` deletes.
# Set SKIP_INSTALL=1 to build without touching /Applications.
INSTALLED="/Applications/Livecall.app"
if [ -n "${SKIP_INSTALL:-}" ]; then
  echo "Skipped install (SKIP_INSTALL set)."
elif [ "$(git -C "$REPO_ROOT" rev-parse --git-dir 2>/dev/null)" \
    != "$(git -C "$REPO_ROOT" rev-parse --git-common-dir 2>/dev/null)" ]; then
  echo "Worktree build — not installing (it would bake $REPO_ROOT into /Applications)."
elif rm -rf "$INSTALLED" && ditto "$APP" "$INSTALLED"; then
  echo "Installed: $INSTALLED"
  pgrep -qf "$INSTALLED/Contents/MacOS/Livecall" && echo "  (still running the old build — quit it from the menu bar and reopen)" || true
else
  echo "⚠️  Could not install to $INSTALLED — the build above is still fine."
fi
